"""App icon for IndicPhotoOCR 2.0 (added for 7.3).

Design: a navy camera viewfinder framing the Devanagari letter "अ" (logo orange) and the Latin "A" (logo blue),
with a green scan line underneath: the three colours of the IndicPhotoOCR wordmark on a white tile.

Writes
  android/app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive-icon foreground (108 dp canvas)
  android/app/src/main/res/drawable/ic_launcher.xml               full square icon, used inside the app
  android/app/src/main/res/mipmap-anydpi-v26/ic_launcher{,_round}.xml
  store/icon_512.png, store/feature_graphic_1024x500.png          Play Store listing graphics
Needs: fonttools (glyph outlines) and Pillow (PNG rendering).
Usage: python tools/make_icon.py   (run from mobile_app/)
"""
import os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.recordingPen import RecordingPen

DEVA = "/usr/share/fonts/truetype/lohit-devanagari/Lohit-Devanagari.ttf"
LATN = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
NAVY, ORANGE, BLUE, GREEN, WHITE = "#23266E", "#FF9900", "#0000FF", "#00C853", "#FFFFFF"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android/app/src/main/res")


def glyph(font_path, ch, x, baseline, height):
    """Outline of one character, scaled so its ink height is `height`, left edge at x, ink bottom at baseline."""
    f = TTFont(font_path)
    gs = f.getGlyphSet()
    name = f.getBestCmap()[ord(ch)]
    rec = RecordingPen(); gs[name].draw(rec)
    from fontTools.pens.boundsPen import BoundsPen
    bp = BoundsPen(gs); gs[name].draw(bp)
    x0, y0, x1, y1 = bp.bounds
    s = height / (y1 - y0)
    # font units are y-up; Android vectors are y-down
    t = (s, 0, 0, -s, x - x0 * s, baseline + y0 * s)
    sp = SVGPathPen(gs); rec.replay(TransformPen(sp, t))
    return sp.getCommands(), (x1 - x0) * s


def letter_metrics(width=40.0, gap_frac=0.12):
    """Letter height so that अ + gap + A spans `width` canvas units; baseline so the group + scan line is centred."""
    _, wd = glyph(DEVA, "अ", 0, 0, 1.0)
    _, wl = glyph(LATN, "A", 0, 0, 0.86)
    h = width / (wd + wl + gap_frac)
    gap = gap_frac * h
    base = 54 + (h + 8.0) / 2 - 8.0   # letters (h) + 5 gap + 3 scan line, centred at 54
    return h, gap, base


def layout(ox=0.0, oy=0.0, k=1.0):
    """Shapes on a 108-unit canvas (adaptive-icon safe zone is the central 66 units: 21..87)."""
    P = lambda v: v  # coordinates already in canvas units
    h, gap, base = letter_metrics()
    _, wd = glyph(DEVA, "अ", 0, 0, h)
    _, wl = glyph(LATN, "A", 0, 0, h * 0.86)
    total = wd + gap + wl
    x0 = 54 - total / 2
    deva, _ = glyph(DEVA, "अ", x0, base, h)
    latn, _ = glyph(LATN, "A", x0 + wd + gap, base, h * 0.86)
    corners = "M28,40 v-12 h12 M68,28 h12 v12 M80,68 v12 h-12 M40,80 h-12 v-12"
    scan = (x0, base + 5.0, total, 3.0)
    return deva, latn, corners, scan


def vector(with_background):
    deva, latn, corners, (sx, sy, sw, sh) = layout()
    bg = ""
    # Adaptive-icon foreground: only the central circle of radius 33 (of 108) is sure to be visible under every
    # launcher mask (a Pixel circle cut the viewfinder tips at radius ~39). Scale it by 0.8 about the centre -> ~31.
    group_open, group_close = "", ""
    if not with_background:
        group_open = '    <group android:pivotX="54" android:pivotY="54" android:scaleX="0.8" android:scaleY="0.8">\n'
        group_close = "    </group>\n"
    if with_background:
        bg = f'    <path android:fillColor="{WHITE}" android:pathData="M18,0h72a18,18 0 0 1 18,18v72a18,18 0 0 1 -18,18h-72a18,18 0 0 1 -18,-18v-72a18,18 0 0 1 18,-18z" />\n'
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile_app/tools/make_icon.py: viewfinder framing अ and A, IndicPhotoOCR logo colours -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
{bg}{group_open}    <path android:strokeColor="{NAVY}" android:strokeWidth="4.5" android:strokeLineCap="round" android:strokeLineJoin="round"
        android:fillColor="#00000000" android:pathData="{corners}" />
    <path android:fillColor="{ORANGE}" android:strokeColor="{ORANGE}" android:strokeWidth="0.8" android:pathData="{deva}" />
    <path android:fillColor="{BLUE}" android:pathData="{latn}" />
    <path android:fillColor="{GREEN}" android:pathData="M{sx:.2f},{sy:.2f} h{sw:.2f} v{sh:.2f} h-{sw:.2f} z" />
{group_close}</vector>
'''


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)
    print("wrote", os.path.relpath(path, ROOT))


ADAPTIVE = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/icon_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
'''


def render_png(size, out, feature=False):
    """Raster versions for the Play Store, drawn with Pillow from the same fonts and layout."""
    from PIL import Image, ImageDraw, ImageFont
    S = 4  # supersampling
    if not feature:
        W = H = size * S
        im = Image.new("RGBA", (W, H), WHITE)
        k = W / 108.0
        ox = oy = 0.0
    else:
        W, H = 1024 * S, 500 * S
        im = Image.new("RGBA", (W, H), WHITE)
        k = H / 108.0 * 0.8
        ox, oy = 30 * S, (H - 108 * k) / 2
    d = ImageDraw.Draw(im)
    # viewfinder corners
    lw = int(4.5 * k)
    for seg in [((28, 40), (28, 28), (40, 28)), ((68, 28), (80, 28), (80, 40)), ((80, 68), (80, 80), (68, 80)), ((40, 80), (28, 80), (28, 68))]:
        pts = [(ox + x * k, oy + y * k) for x, y in seg]
        d.line(pts, fill=NAVY, width=lw, joint="curve")
        for p in (pts[0], pts[-1]):
            d.ellipse([p[0] - lw / 2, p[1] - lw / 2, p[0] + lw / 2, p[1] + lw / 2], fill=NAVY)
    # letters: same metrics as the vector
    H0, gap, base = letter_metrics()
    _, wd = glyph(DEVA, "अ", 0, 0, H0)
    _, wl = glyph(LATN, "A", 0, 0, H0 * 0.86)
    total = wd + gap + wl
    x0 = 54 - total / 2
    for font, ch, x, h, col in [(DEVA, "अ", x0, H0, ORANGE), (LATN, "A", x0 + wd + gap, H0 * 0.86, BLUE)]:
        fnt = ImageFont.truetype(font, 400)
        bb = d.textbbox((0, 0), ch, font=fnt)
        scale = h * k / (bb[3] - bb[1])
        fnt = ImageFont.truetype(font, int(400 * scale))
        bb = d.textbbox((0, 0), ch, font=fnt)
        d.text((ox + x * k - bb[0], oy + base * k - bb[3]), ch, font=fnt, fill=col,
               stroke_width=int(0.4 * k) if font == DEVA else 0, stroke_fill=col)
    d.rectangle([ox + x0 * k, oy + (base + 5) * k, ox + (x0 + total) * k, oy + (base + 8) * k], fill=GREEN)
    if feature:
        f1 = ImageFont.truetype(LATN, 56 * S)
        f2 = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 28 * S)
        tx = ox + 100 * k + 10 * S
        d.text((tx, 160 * S), "IndicPhotoOCR", font=f1, fill=NAVY)
        d.text((tx, 250 * S), "Read text in photos, offline", font=f2, fill="#5D6075")
        d.text((tx, 296 * S), "English + 11 Indian languages", font=f2, fill="#5D6075")
        for i, c in enumerate([ORANGE, BLUE, GREEN]):
            d.rectangle([tx + i * 110 * S, 370 * S, tx + (i + 1) * 110 * S - 8 * S, 378 * S], fill=c)
    im = im.resize((W // S, H // S), Image.LANCZOS).convert("RGB")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    im.save(out)
    print("wrote", os.path.relpath(out, ROOT))


if __name__ == "__main__":
    write(os.path.join(RES, "drawable/ic_launcher_foreground.xml"), vector(False))
    write(os.path.join(RES, "drawable/ic_launcher.xml"), vector(True))
    write(os.path.join(RES, "mipmap-anydpi-v26/ic_launcher.xml"), ADAPTIVE)
    write(os.path.join(RES, "mipmap-anydpi-v26/ic_launcher_round.xml"), ADAPTIVE)
    try:
        render_png(512, os.path.join(ROOT, "store/icon_512.png"))
        render_png(0, os.path.join(ROOT, "store/feature_graphic_1024x500.png"), feature=True)
    except ImportError:
        print("Pillow not installed: Play Store PNGs skipped")
